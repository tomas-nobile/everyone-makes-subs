export type Lang = 'es' | 'en' | 'pt';
export const SUPPORTED_LANGS: Lang[] = ['es', 'en', 'pt'];

export function isLang(v: string | null | undefined): v is Lang {
  return v === 'es' || v === 'en' || v === 'pt';
}

/** `?lang=` wins; otherwise the first matching `navigator.language` prefix; otherwise `fallback`. */
export function detectLang(queryLang: string | null, fallback: Lang = 'en'): Lang {
  if (isLang(queryLang)) return queryLang;
  const nav = typeof navigator !== 'undefined' ? navigator.language.slice(0, 2).toLowerCase() : '';
  if (isLang(nav)) return nav;
  return fallback;
}

export interface LangMeta {
  name: string; // the language's own name, e.g. "English"
  sound: string; // "applause" chip word
  speaking: string; // "speaking…" word while a phrase is mid-translation
}

