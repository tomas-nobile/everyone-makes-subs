/** "original" / "translation" label, relative to the talk's own language. */
export function subLabel(lang: Lang, isOriginal: boolean): string {
  if (isOriginal) return lang === 'es' ? 'original' : lang === 'pt' ? 'idioma original' : 'original';
  return lang === 'es' ? 'traducción' : lang === 'pt' ? 'tradução' : 'translation';
}

